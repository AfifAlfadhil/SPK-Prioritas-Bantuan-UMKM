def seed_sample_umkm(conn) -> int:
    """Isi data UMKM jika tabel umkm masih kosong. Kembalikan jumlah baris yang dimasukkan."""
    count = conn.execute("SELECT COUNT(*) FROM umkm").fetchone()[0]
    if count > 0:
        return 0

    inserted = 0
    now_str = datetime.now(timezone.utc).isoformat(timespec="seconds")
    for u in SAMPLE_UMKM:
        conn.execute(
            """
            INSERT INTO umkm (
                source_id, nama_usaha, pemilik, jenis_usaha, kecamatan, kelurahan,
                nib, modal_usaha, omzet_bulanan, jumlah_tenaga_kerja,
                lama_usaha_bulan, tingkat_digitalisasi, akses_permodalan,
                riwayat_bantuan, updated_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                u["source_id"], u["nama_usaha"], u["pemilik"], u["jenis_usaha"],
                u["kecamatan"], u["kelurahan"], u["nib"], u["modal_usaha"],
                u["omzet_bulanan"], u["jumlah_tenaga_kerja"], u["lama_usaha_bulan"],
                u["tingkat_digitalisasi"], u["akses_permodalan"], u["riwayat_bantuan"],
                now_str,
            ),
        )
        inserted += 1
    conn.commit()
    return inserted
